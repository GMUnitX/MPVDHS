# -*- coding: utf-8 -*-
"""
MPVDHS 全局配置
================================================================
多路径并行解码 + 动态幻觉抑制推理系统

本文件按功能分块，所有可调参数集中在这里，每一项都有明确标注。
修改参数不需要改动任何其他代码。
"""

# ============================================================================
# 分块 1：模型与设备（规则1、2）
# ============================================================================

# 模型路径：本地目录或 HuggingFace 模型名（如果是名字，首次运行会自动下载）
MODEL_PATH = r".\models\Qwen\Qwen2.5-0.5B-Instruct"

# 设备选择策略：
#   "auto" —— 自动选择（检测到可用的 CUDA GPU 就用 GPU，否则用 CPU）
#   "cuda" —— 强制 GPU（没有可用 GPU 时报错）
#   "cpu"  —— 强制 CPU
DEVICE_MODE = "auto"

# GPU 上的权重精度："fp16"（推荐）/ "bf16"（需要安培及以上架构）/ "fp32"
GPU_DTYPE = "fp16"

# CPU 上的权重精度："fp32"（推荐，最稳定）/ "bf16"（更快，但老 CPU 可能不支持）
CPU_DTYPE = "fp32"

# 注意力实现方式，必须保持 "eager"：
# 默认的 SDPA / FlashAttention 后端无法返回逐 token 的注意力权重，而本系统的
# 规则5 依赖注意力权重，因此加载模型时强制使用 eager 实现。
ATTN_IMPLEMENTATION = "eager"

# 是否信任模型目录里的自定义代码（官方 Qwen / Llama 等保持 False 即可）
TRUST_REMOTE_CODE = False

# ============================================================================
# 分块 2：并行路径数量（规则4）
# ============================================================================

# 每个步骤并行推理的路径数 n。
# 路径越多，分歧检测越可靠，但内存占用和耗时大致按 n 倍增长。
NUM_PATHS = 4

# ============================================================================
# 分块 3：采样参数（规则4：n 条路径共用同一套参数）
# ============================================================================

# 温度。注意必须 > 0：temperature = 0 是贪心解码，n 条路径会完全一致，
# 分歧检测（规则8）将永远判定"无分歧"，系统失去意义。
TEMPERATURE = 0.8

# nucleus 截断：只在累积概率达到 top_p 的最小 token 集合内采样。1.0 = 不截断。
TOP_P = 0.95

# top-k 截断：只在概率最高的 top_k 个 token 内采样。0 = 不截断。
TOP_K = 50

# 随机种子：固定后每次运行可复现；None = 每次运行用新的随机流。
SEED = 42

# ============================================================================
# 分块 4：步骤与长度上限（安全阀，防止跑飞）
# ============================================================================

# 一次回复最多包含多少个"步骤"（规则8/9 的步骤循环次数上限）
MAX_STEPS = 8

# 单条路径在单个步骤内最多生成的 token 数。
# 达到上限仍未触发"注意力相似度低于阈值"或 EOS 时，强制按"步骤完成"结束该路径。
MAX_STEP_TOKENS = 96

# 一次回复所有步骤累计新增 token 的硬上限。
MAX_TOTAL_NEW_TOKENS = 512

# ============================================================================
# 分块 5：注意力监测（规则5）
# ============================================================================

# 相邻两个 token 的注意力权重（最后一层、按注意力头取平均）在"公共历史部分"
# （双方都去掉自己所在位置）上的余弦相似度低于该阈值时，视为到达"该步骤末尾"，
# 结束原因标记为"步骤完成"。
# 用 diagnose_attention.py 可实测当前模型的相似度分布来校准本阈值：
# 实测 Qwen2.5-0.5B 多数 token 在 0.92~0.99，真正的语义转折点会跌到 0.5~0.6；
# 0.85 ≈ P10 水平（约 10% 的 token 触发步骤末尾）。调小 → 步骤更长，调大 → 步骤更碎。
ATTN_SIM_THRESHOLD = 0.85

# 参与相似度计算的公共历史部分的最短长度，短于该值时不做比较
#（防止序列太短时注意力向量抖动造成误触发）。
ATTN_MIN_COMMON_LEN = 1

# ============================================================================
# 分块 6：置信度监测（规则6）
# ============================================================================

# 每个 token 的置信度 = 采样该 token 时模型原始分布（不乘温度）的最高概率。
# 低于该阈值 → 该路径"提前终止"（其注意力/隐藏状态/置信度序列全部作废）。
# 调试建议：0.05 ~ 0.30 之间试探；调大 → 提前终止更频繁。
CONFIDENCE_THRESHOLD = 0.10

# 计算几何平均置信度时防止 log(0) 的极小值保护。
GEO_MEAN_EPS = 1e-12

# ============================================================================
# 分块 7：分歧分析（规则8）
# ============================================================================

# FastDTW 对齐后，在对齐路径长度的该比例处切分"头部/尾部"
#（例如 0.30 = 对齐序列的前 30% 为头部，其余为尾部）。
HEAD_SPLIT_RATIO = 0.30

# 头部平均余弦相似度低于该阈值 → "创造性分歧"
#（保留置信度最高路径的 KV 缓存，清除其余，直接进入下一步骤）。
HEAD_SIM_THRESHOLD = 0.90

# 头部达标但尾部平均余弦相似度低于该阈值 → "错误性分歧"
#（保留置信度最高路径的 KV 缓存 + 强制追加 <self-check>，进入下一步骤）。
# 头尾都达标 → "无分歧"（同创造性分歧处理，不加 <self-check>）。
TAIL_SIM_THRESHOLD = 0.90

# FastDTW 的 radius 参数：越大对齐越精确但越慢（1~3 通常足够）。
FASTDTW_RADIUS = 1

# ============================================================================
# 分块 8：<self-check> 标记（规则8、9）
# ============================================================================

# 强制拼接的标记文本。
SELF_CHECK_TOKEN = "<self-check>"

# True  —— 注册为单个特殊 token 并扩展词表 embedding
#          （适合你后续微调模型、让模型真正"认识"这个标记）；
# False —— 按普通文本分词成若干子词后拼接（不改动模型本身，通用、安全，推荐）。
SELF_CHECK_AS_SPECIAL = False

# <self-check> 标记本身是否计入最终展示文本（无论真假，它都会拼进 KV 缓存）。
SELF_CHECK_SHOW_IN_OUTPUT = False

# ============================================================================
# 分块 9：日志与调试
# ============================================================================

# True —— 每个步骤结束时在控制台打印：各路径状态/结束原因/token数/几何平均置信度、
#         头尾相似度、分歧判定、保留路径等详细信息。
VERBOSE = True
